"""Generates docs/cards.md from content/cards.json (023), and checks the set's shape.

    python scripts/cards/cards_doc.py           # writes docs/cards.md, prints the shape
    python scripts/cards/cards_doc.py --check   # exits 1 if docs/cards.md is stale

Cards are listed by primary tag (the first printed tag), then tier, then name. The
AI-unique cards (tier 0) come last. The shape table compares the draft decks with
023's targets (about 150 cards, 110 / 40 by tier, 60 / 25 / 15 % programs / buildings /
events, 60 / 30 / 10 % one / two / three tags, ~25 primary per tag, insight 25 / 50 /
25 % at 0 / 1 / 2, ~10% help cards).
"""
import collections
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TAGS = ['science', 'industry', 'cyber', 'power', 'diplomacy', 'security']
KINDS = ['program', 'building', 'event']


def revision():
    with open(os.path.join(ROOT, 'crates', 'aic-core', 'src', 'lib.rs'), encoding='utf-8') as f:
        return re.search(r'RULES_REVISION: u32 = (\d+)', f.read())[1]


def load():
    with open(os.path.join(ROOT, 'content', 'cards.json'), encoding='utf-8') as f:
        return json.load(f)


def deck_ids():
    with open(os.path.join(ROOT, 'configs', 'baseline.json'), encoding='utf-8') as f:
        cfg = json.load(f)
    for m in cfg['modules']:
        if m['module'] == 'cards':
            return set(m['cards'])
    return set()


def cost_text(c):
    parts = [f"{c.get('cost', 0)} cr"]
    for k, short in [('energy', 'en'), ('chips', 'ch'), ('antimatter', 'am')]:
        if c.get(k):
            parts.append(f'{c[k]} {short}')
    for r, n in c.get('lowers', []):
        parts.append(f'-{n} {r} income')
    if c.get('needs'):
        parts.append('needs ' + ', '.join(f'{n} {t}' for t, n in c['needs']))
    if c.get('replaces'):
        parts.append(f"over {c['replaces']}")
    return '; '.join(parts)


def pct(n, d):
    return f'{100 * n / d:.0f}%' if d else '-'


def shape(cards):
    deck = [c for c in cards if c['tier'] in (1, 2)]
    n = len(deck)
    out = ['| measure | count | share | target |', '|---|---|---|---|']
    out.append(f'| cards in the draft decks | {n} | | ~150 |')
    for t in (1, 2):
        k = sum(c['tier'] == t for c in deck)
        out.append(f"| tier {t} | {k} | {pct(k, n)} | {'~110' if t == 1 else '~40'} |")
    for kind, target in zip(KINDS, ['60%', '25%', '15%']):
        k = sum(c['kind'] == kind for c in deck)
        out.append(f'| {kind}s | {k} | {pct(k, n)} | {target} |')
    for nt, target in [(1, '60%'), (2, '30%'), (3, '10%')]:
        k = sum(len(c['tags']) == nt for c in deck)
        out.append(f'| {nt} tag(s) | {k} | {pct(k, n)} | {target} |')
    for ins, target in [(0, '25%'), (1, '50%'), (2, '25%')]:
        k = sum(c.get('insight', 0) == ins for c in deck)
        out.append(f'| insight {ins} | {k} | {pct(k, n)} | {target} |')
    k = sum('help' in c.get('keywords', []) for c in deck)
    out.append(f'| help cards | {k} | {pct(k, n)} | ~10% |')
    for t in TAGS:
        prim = sum(c['tags'][0] == t for c in deck)
        anyt = sum(t in c['tags'] for c in deck)
        out.append(f'| primary {t} (on any) | {prim} ({anyt}) | | ~25 |')
    big = sum(c.get('cost', 0) >= 25 for c in deck)
    out.append(f'| credits 25+ | {big} | | a handful, none over ~50 |')
    am = [c['name'] for c in deck if c.get('antimatter')]
    out.append(f"| antimatter cost | {len(am)} | | tier-2 ultimates only |")
    return '\n'.join(out)


def render(cards):
    deck = deck_ids()
    lines = [
        '# The player cards',
        '',
        'Generated by `python scripts/cards/cards_doc.py` from `content/cards.json`: do not',
        f'edit by hand. Rules revision {revision()}. Every card is a **candidate**. Sorted by',
        'primary tag (the first printed tag), then tier, then name; the AI-unique cards',
        '(tier 0) close the list. Costs: credits (cr), energy (en), chips (ch),',
        'antimatter (am), income lowered for the rest of the game, the tags a card needs on',
        'your buildings, and the tag of the building a replacement is built over. Insight is',
        'the insight to play it; keeping a drafted card costs 1 insight (tier 1) or 3 (tier 2)',
        'on top. A card marked *(not in deck)* is in the content but not in the baseline',
        "config's card list.",
        '',
        '## Shape',
        '',
        shape(cards),
        '',
    ]
    def key(c):
        tier = c['tier'] if c['tier'] else 9
        prim = TAGS.index(c['tags'][0]) if c['tags'] else 9
        return (tier == 9, prim, tier, c['name'])
    groups = collections.OrderedDict()
    for c in sorted(cards, key=key):
        g = 'AI-unique cards' if c['tier'] == 0 else c['tags'][0].capitalize()
        groups.setdefault(g, []).append(c)
    for g, cs in groups.items():
        lines += [f'## {g} ({len(cs)})', '',
                  '| card | tier | kind | cost | insight | tags | effect |',
                  '|---|---|---|---|---|---|---|']
        for c in cs:
            name = c['name']
            if c['tier'] in (1, 2) and c['id'] not in deck:
                name += ' *(not in deck)*'
            kw = c.get('keywords', [])
            kind = c['kind'] + (' (help)' if 'help' in kw else '')
            text = c.get('text', '').replace('|', '/')
            lines.append(
                f"| {name} | {c['tier'] or '-'} | {kind} | {cost_text(c)} | "
                f"{c.get('insight', 0)} | {', '.join(c['tags'])} | {text} |")
        lines.append('')
    return '\n'.join(lines)


def main(argv):
    cards = load()
    text = render(cards)
    path = os.path.join(ROOT, 'docs', 'cards.md')
    if '--check' in argv:
        with open(path, encoding='utf-8') as f:
            if f.read() != text:
                print('docs/cards.md is stale: run python scripts/cards/cards_doc.py')
                return 1
        return 0
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(shape(cards))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
